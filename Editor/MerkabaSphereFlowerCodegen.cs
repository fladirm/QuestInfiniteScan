using System;
using System.Globalization;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace Genesis.RoomScan.Editor
{
    /// <summary>
    /// CUT 0 bootstrap for the one REV-B table generator. CUT 1 replaces the
    /// bootstrap body with the exhaustive symbolic oracle/code generator.
    /// </summary>
    public static class MerkabaSphereFlowerCodegen
    {
        public const string GeneratedAssetPath =
            "Packages/com.genesis.roomscan/Runtime/Shaders/MerkabaSphereFlower.generated.hlsl";

        [MenuItem("Quest Infinite Scan/Merkaba/Regenerate Sphere-Flower HLSL")]
        public static void Regenerate()
        {
            string path = Path.GetFullPath(GeneratedAssetPath);
            string expected = BuildBootstrapHlsl();
            if (!File.Exists(path) || !string.Equals(File.ReadAllText(path),
                    expected, StringComparison.Ordinal))
            {
                File.WriteAllText(path, expected);
                AssetDatabase.ImportAsset(GeneratedAssetPath,
                    ImportAssetOptions.ForceSynchronousImport);
            }
            Debug.Log($"[SphereFlower] Generated bootstrap HLSL: {path}");
        }

        public static void GenerateForBatch() => Regenerate();

        public static void CheckForBatch()
        {
            string path = Path.GetFullPath(GeneratedAssetPath);
            if (!File.Exists(path))
                throw new FileNotFoundException(
                    "Generated Sphere-Flower HLSL is missing.", path);
            string actual = File.ReadAllText(path);
            string expected = BuildBootstrapHlsl();
            if (!string.Equals(actual, expected, StringComparison.Ordinal))
                throw new InvalidDataException(
                    "MerkabaSphereFlower.generated.hlsl is stale.");
        }

        internal static string BuildBootstrapHlsl()
        {
            var output = new StringBuilder(512);
            output.AppendLine("// GENERATED by MerkabaSphereFlowerCodegen. DO NOT EDIT.");
            output.AppendLine("// CUT 0 schema only; no production shader includes this file yet.");
            output.AppendLine("#ifndef GENESIS_MERKABA_SPHERE_FLOWER_INCLUDED");
            output.AppendLine("#define GENESIS_MERKABA_SPHERE_FLOWER_INCLUDED");
            output.Append("#define M8_FLOWER_LATTICE_STEP ")
                .Append(MerkabaSphereFlowerAuthority.LatticeStep.ToString("R",
                    CultureInfo.InvariantCulture)).AppendLine();
            output.Append("#define M8_FLOWER_LEVEL_COUNT ")
                .Append(MerkabaSphereFlowerAuthority.LevelCount).AppendLine();
            output.Append("#define M8_FLOWER_LINE_CLASS_COUNT ")
                .Append(MerkabaSphereFlowerAuthority.LineClassCount).AppendLine();
            output.Append("#define M8_FLOWER_NODE_CLASS_COUNT ")
                .Append(MerkabaSphereFlowerAuthority.NodeClassCount).AppendLine();
            output.Append("#define M8_FLOWER_STRAND_CLASS_COUNT ")
                .Append(MerkabaSphereFlowerAuthority.StrandClassCount).AppendLine();
            output.Append("#define M8_FLOWER_PETAL_CLASS_COUNT ")
                .Append(MerkabaSphereFlowerAuthority.PetalClassCount).AppendLine();
            output.AppendLine("#endif");
            return output.ToString();
        }
    }
}
