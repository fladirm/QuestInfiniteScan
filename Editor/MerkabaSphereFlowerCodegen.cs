{
    M8FlowerPhaseResidualResult result;
    result.Classification=classification;
    result.Residual=M8FlowerI(0.0,0.0);
    result.Synthesis.x=M8FlowerI(0.0,0.0);
    result.Synthesis.y=result.Synthesis.x;
    result.Lower=0;
    result.Upper=0;
