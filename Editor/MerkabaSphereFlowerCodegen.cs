struct M8FlowerDyadicSquare
{
    uint2 coefficient;
    int exponent;
    uint nonzero;
};

uint2 M8FlowerMultiply24(uint a, uint b)
{
    uint a0 = a & 0xffffu;
    uint a1 = a >> 16;
    uint b0 = b & 0xffffu;
    uint b1 = b >> 16;
    uint p0 = a0*b0;
    uint p1 = a0*b1+a1*b0;
    uint lo = p0+(p1 << 16);
    uint carry = lo < p0 ? 1u : 0u;
    uint hi = (p1 >> 16)+a1*b1+carry;
    return uint2(lo,hi);
}

M8FlowerDyadicSquare M8FlowerSquareDyadic(float value)
{
    M8FlowerDyadicSquare result;
    uint bits = asuint(abs(value));
    uint exponentBits = (bits >> 23) & 0xffu;
    uint mantissa = bits & 0x7fffffu;
    result.nonzero = 0u;
    result.coefficient = 0u.xx;
    result.exponent = 0;
    if (exponentBits == 0xffu)
    {
        result.nonzero = 2u;
        return result;
    }
    if (exponentBits == 0u && mantissa == 0u)
        return result;
    int exponent = exponentBits == 0u ? -149 : (int)exponentBits-127-23;
    if (exponentBits != 0u) mantissa |= 0x800000u;
    int trailing = firstbitlow(mantissa);
    mantissa >>= trailing;
    exponent += trailing;
    result.coefficient = M8FlowerMultiply24(mantissa,mantissa);
    result.exponent = exponent*2;
    result.nonzero = 1u;
    return result;
}

