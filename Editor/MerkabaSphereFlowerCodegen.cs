bool M8FlowerRoot(float3 abc, bool plusRoot, out float2 root)
{
    precise float q = abc.y*abc.y+abc.z*abc.z;
    precise float delta = q-abc.x*abc.x;
    if (!(q > 0.0) || delta < 0.0) { root = 0.0.xx; return false; }
    precise float d = sqrt(delta);
    precise float s = plusRoot ? 1.0 : -1.0;
    root = float2((-abc.x*abc.y + s*d*-abc.z)/q,
        (-abc.x*abc.z + s*d*abc.y)/q);
    return true;
}

bool M8FlowerTau(float2 from, float2 to, out float turn)
{
    precise float denominator = 1.0+dot(from,to);
    if (denominator == 0.0) { turn = 0.0; return false; }
    turn = (from.x*to.y-from.y*to.x)/denominator;
    return true;
}

float2 M8FlowerRotate(float2 root, float turn)
{
    precise float rr = turn*turn;
    precise float inverse = 1.0/(1.0+rr);
    precise float c = (1.0-rr)*inverse;
    precise float s = 2.0*turn*inverse;
    return float2(c*root.x-s*root.y,s*root.x+c*root.y);
}

