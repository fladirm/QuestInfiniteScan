    return float4(scalar+dot(M8FlowerTetraAxis[0],tetraVector),
        scalar+dot(M8FlowerTetraAxis[1],tetraVector),
        scalar+dot(M8FlowerTetraAxis[2],tetraVector),
        scalar+dot(M8FlowerTetraAxis[3],tetraVector));
}

