        [MenuItem("Quest Infinite Scan/Merkaba/Regenerate Sphere-Flower HLSL")]
        public static void Regenerate()
        {
            // Resolve every algebra/ABI proof before publishing any consumer.
            // A failed sector or child proof must not leave HLSL from a new
            // authority beside C# or native tables from the previous one.
            string hlsl = BuildGeneratedHlsl();
            string csharp = BuildGeneratedCs();
            string dataAbi = BuildGeneratedDataAbiHlsl();
            string nativeAbi = BuildGeneratedNativeDataAbi();
            string depthCertificate = BuildDepthCertificateHlsl();
            WriteIfChanged(GeneratedAssetPath, hlsl);
            WriteIfChanged(GeneratedCsAssetPath, csharp);
            WriteIfChanged(GeneratedDataAbiAssetPath, dataAbi);
            WriteIfChanged(GeneratedNativeDataAbiAssetPath, nativeAbi);
            WriteIfChanged(GeneratedDepthCertificateAssetPath, depthCertificate);
            Debug.Log("[SphereFlower] Generated exact CPU/HLSL tables.");
        }

        public static void GenerateForBatch() => Regenerate();

        public static void CheckForBatch()
        {
            CheckExact(GeneratedAssetPath, BuildGeneratedHlsl());
            CheckExact(GeneratedCsAssetPath, BuildGeneratedCs());
            CheckExact(GeneratedDataAbiAssetPath, BuildGeneratedDataAbiHlsl());
            CheckExact(GeneratedNativeDataAbiAssetPath,
                BuildGeneratedNativeDataAbi());
            CheckExact(GeneratedDepthCertificateAssetPath, BuildDepthCertificateHlsl());
        }

        private static void WriteIfChanged(string assetPath, string expected)
        {
            string path = Path.GetFullPath(assetPath);
            if (File.Exists(path) && string.Equals(File.ReadAllText(path),
                    expected, StringComparison.Ordinal)) return;
            File.WriteAllText(path, expected);
            AssetDatabase.ImportAsset(assetPath,
                ImportAssetOptions.ForceSynchronousImport);
        }

        private static void CheckExact(string assetPath, string expected)
        {
            string path = Path.GetFullPath(assetPath);
            if (!File.Exists(path))
                throw new FileNotFoundException(
                    "Generated Sphere-Flower table is missing.", path);
            if (!string.Equals(File.ReadAllText(path), expected,
                    StringComparison.Ordinal))
                throw new InvalidDataException(
                    $"Generated Sphere-Flower table is stale: {assetPath}");
        }

