bool M8FlowerEndpointPair(int3 junction, uint lineClass,
    out int3 first, out int3 second)
{
    int3 direction = M8FlowerLineDirection[lineClass];
    int3 doubled = junction-direction;
    if (any((asuint(doubled) & 1u) != 0u))
    {
        first = 0;
        second = 0;
        return false;
    }
    first = doubled >> 1;
    second = first+direction;
    return true;
}

