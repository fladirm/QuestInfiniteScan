uint M8FlowerRank49(uint2 mask, uint bit)
{
    mask.y&=0x1ffffu;
    if (bit<=32u)
    {
        uint below=bit==0u ? 0u :
            (bit==32u ? 0xffffffffu : (1u<<bit)-1u);
        return countbits(mask.x&below);
    }
    uint highBit=bit-32u;
    uint highBelow=highBit==0u ? 0u : (1u<<highBit)-1u;
    return countbits(mask.x)+countbits(mask.y&highBelow);
}

