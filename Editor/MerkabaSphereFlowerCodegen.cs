    return uint2((value.x >> 1) | (value.y << 31),value.y >> 1);
}

bool M8FlowerExactSquaredEquality(float a, float b, float c)
{
    M8FlowerDyadicSquare sa = M8FlowerSquareDyadic(a);
    M8FlowerDyadicSquare sb = M8FlowerSquareDyadic(b);
    M8FlowerDyadicSquare sc = M8FlowerSquareDyadic(c);
    if (sa.nonzero == 2u || sb.nonzero == 2u || sc.nonzero == 2u)
        return false;
    if (sb.nonzero == 0u && sc.nonzero == 0u)
        return sa.nonzero == 0u;
    if (sa.nonzero == 0u) return false;
    if (sb.nonzero == 0u)
        return sa.exponent == sc.exponent &&
            M8FlowerEqual64(sa.coefficient,sc.coefficient);
    if (sc.nonzero == 0u)
        return sa.exponent == sb.exponent &&
            M8FlowerEqual64(sa.coefficient,sb.coefficient);

    if (sb.exponent == sc.exponent)
    {
        uint2 sum = M8FlowerAdd64(sb.coefficient,sc.coefficient);
        return sa.exponent == sb.exponent+1 &&
            M8FlowerEqual64(sa.coefficient,M8FlowerShiftRightOne64(sum));
    }

    M8FlowerDyadicSquare low;
    M8FlowerDyadicSquare high;
    if (sb.exponent < sc.exponent)
    {
        low = sb;
        high = sc;
    }
    else
    {
        low = sc;
        high = sb;
    }
    int difference = high.exponent-low.exponent;
    if (sa.exponent != low.exponent || difference >= 64)
        return false;
    uint highBits = M8FlowerBitLength(high.coefficient);
    uint leftBits = M8FlowerBitLength(sa.coefficient);
    if (highBits+(uint)difference > leftBits)
        return false;
    uint2 sum = M8FlowerAdd64(low.coefficient,
        M8FlowerShiftLeft64(high.coefficient,(uint)difference));
    return M8FlowerEqual64(sa.coefficient,sum);
}

uint M8FlowerClassifyRoot(M8FlowerInterval3 abc)
{
    if (abc.x.lo == abc.x.hi && abc.y.lo == abc.y.hi &&
        abc.z.lo == abc.z.hi &&
        M8FlowerExactSquaredEquality(abc.x.lo,abc.y.lo,abc.z.lo))
        return abc.y.lo == 0.0 && abc.z.lo == 0.0 ?
            M8_FLOWER_ROOT_COPLANAR : M8_FLOWER_ROOT_CERTAIN_TANGENT;
    M8FlowerInterval q = M8FlowerIAdd(M8FlowerISquare(abc.y),
        M8FlowerISquare(abc.z));
    M8FlowerInterval aa = M8FlowerISquare(abc.x);
    if (q.lo == 0.0 && q.hi == 0.0)
    {
        if (abc.x.lo == abc.x.hi)
            return abc.x.lo == 0.0 ? M8_FLOWER_ROOT_COPLANAR :
                M8_FLOWER_ROOT_IMPOSSIBLE;
        return abc.x.lo <= 0.0 && abc.x.hi >= 0.0 ?
            M8_FLOWER_ROOT_AMBIGUOUS : M8_FLOWER_ROOT_IMPOSSIBLE;
    }
    if (aa.hi < q.lo) return M8_FLOWER_ROOT_CERTAIN_SECANT;
    if (aa.lo > q.hi) return M8_FLOWER_ROOT_IMPOSSIBLE;
    if (aa.lo == aa.hi && q.lo == q.hi && aa.lo == q.lo && q.lo > 0.0)
        return M8_FLOWER_ROOT_CERTAIN_TANGENT;
    return M8_FLOWER_ROOT_AMBIGUOUS;
}

// Exact dyadic comparisons certify interval products and midpoint decisions.
M8FlowerDyadicSquare M8FlowerProductDyadic(float left, float right)
{
    M8FlowerDyadicSquare result;
    uint2 bits = uint2(asuint(left), asuint(right)) & 0x7fffffffu;
    uint2 e = (bits >> 23u) & 0xffu;
    uint2 m = bits & 0x7fffffu;
    m |= uint2(e.x != 0u ? 0x800000u : 0u,
        e.y != 0u ? 0x800000u : 0u);
    result.coefficient = M8FlowerMultiply24(m.x, m.y);
    result.exponent = (e.x == 0u ? -149 : (int)e.x - 150) +
        (e.y == 0u ? -149 : (int)e.y - 150);
    result.nonzero = any(e == 255u) ? 2u :
        (all(m != 0u) ? 1u : 0u);
    if (result.nonzero == 0u) result.coefficient = 0u.xx;
    return result;
}

int M8FlowerCompareDyadic(M8FlowerDyadicSquare a, M8FlowerDyadicSquare b)
{
    uint na = M8FlowerBitLength(a.coefficient);
    uint nb = M8FlowerBitLength(b.coefficient);
    if (na == 0u || nb == 0u) return na == nb ? 0 : (na == 0u ? -1 : 1);
    int topA = a.exponent + (int)na;
    int topB = b.exponent + (int)nb;
    if (topA != topB) return topA < topB ? -1 : 1;
    uint2 ca = M8FlowerShiftLeft64(a.coefficient, na < nb ? nb - na : 0u);
    uint2 cb = M8FlowerShiftLeft64(b.coefficient, nb < na ? na - nb : 0u);
    if (ca.y != cb.y) return ca.y < cb.y ? -1 : 1;
    return ca.x == cb.x ? 0 : (ca.x < cb.x ? -1 : 1);
}

bool M8FlowerDivideEnclosed(float numerator, float denominator,
    out M8FlowerInterval result)
{
    result = M8FlowerI(0.0, 0.0);
    uint denominatorBits = asuint(denominator);
    if (!M8FlowerIsFinite(numerator) || denominatorBits == 0u ||
        denominatorBits >= 0x7f800000u)
        return false;
    uint sign = asuint(numerator) & 0x80000000u;
    uint magnitude = asuint(numerator) & 0x7fffffffu;
    if (magnitude == 0u) return true;
    uint nEncoded=magnitude>>23u,dEncoded=denominatorBits>>23u;
    uint n=(magnitude&0x7fffffu)|(nEncoded!=0u?0x800000u:0u);
    uint d=(denominatorBits&0x7fffffu)|(dEncoded!=0u?0x800000u:0u);
    int nExponent=nEncoded!=0u?(int)nEncoded-127:-126;
    int dExponent=dEncoded!=0u?(int)dEncoded-127:-126;
    [loop] while(n<0x800000u){n<<=1u;--nExponent;}
    [loop] while(d<0x800000u){d<<=1u;--dExponent;}
    int exponent=nExponent-dExponent;
    if(n<d){n<<=1u;--exponent;}
    if(exponent>127)return false;
    uint lo=0u,hi=1u;
    if(exponent>=-149)
    {
        // d<=n<2d. Integer long division emits exactly the representable
        // significand bits, never more than23; every remainder is <2d.
        uint fractionBits=exponent>=-126?23u:(uint)(exponent+149);
        uint quotient=1u,remainder=n-d;
        [loop] for(uint bit=0u;bit<fractionBits;++bit)
        {
            if(remainder==0u){quotient<<=fractionBits-bit;break;}
            remainder<<=1u;quotient<<=1u;
            if(remainder>=d){remainder-=d;quotient|=1u;}
        }
        lo=exponent>=-126?((uint)(exponent+127)<<23u)|(quotient&0x7fffffu):quotient;
        hi=lo+(remainder!=0u?1u:0u);
        if(hi>=0x7f800000u)return false;
    }
    // Underflow has the exact [0,min-subnormal] enclosure. Subnormal to
    // normal carry is valid; only maxfinite to infinity was rejected above.
    if (sign == 0u) result = M8FlowerI(asfloat(lo),asfloat(hi));
    else result = M8FlowerI(asfloat(hi | sign),asfloat(lo | sign));
    return true;
}

bool M8FlowerIDivPositive(M8FlowerInterval numerator,
    M8FlowerInterval denominator, out M8FlowerInterval result)
{
    result = M8FlowerI(0.0, 0.0);
    uint dLo = asuint(denominator.lo), dHi = asuint(denominator.hi);
    uint nLo = asuint(numerator.lo), nHi = asuint(numerator.hi);
    if (dLo == 0u || dLo > dHi || dHi >= 0x7f800000u ||
        !M8FlowerIsFinite(numerator.lo) || !M8FlowerIsFinite(numerator.hi)) return false;
    // Compare finite values and choose denominator endpoints by bits.
    // Shader FP comparisons may flush a nonzero subnormal to signed zero.
    if ((nLo & 0x7fffffffu) == 0u) nLo = 0u;
    if ((nHi & 0x7fffffffu) == 0u) nHi = 0u;
    bool lowerNegative = (nLo >> 31u) != 0u;
    bool upperNegative = (nHi >> 31u) != 0u;
    uint lowerOrder = lowerNegative ? ~nLo : nLo | 0x80000000u;
    uint upperOrder = upperNegative ? ~nHi : nHi | 0x80000000u;
    if (lowerOrder > upperOrder) return false;
    float2 numerators = float2(numerator.lo,numerator.hi);
    float2 denominators = float2(lowerNegative ? denominator.lo : denominator.hi,
        upperNegative ? denominator.hi : denominator.lo);
    float2 endpoints = 0.0;
    [loop] for(uint endpoint=0u;endpoint<2u;endpoint++)
    {
        M8FlowerInterval enclosed;
        if(!M8FlowerDivideEnclosed(numerators[endpoint],denominators[endpoint],enclosed))return false;
        endpoints[endpoint]=endpoint==0u?enclosed.lo:enclosed.hi;
    }
    result = M8FlowerI(endpoints.x,endpoints.y);
    return true;
}

// The canonical rounding implementation follows the interval primitives
// whose exact dyadic enclosure it reuses.
float M8FlowerRoundSqrt(float value);

bool M8FlowerISqrt(M8FlowerInterval value, out M8FlowerInterval result)
{
    result = M8FlowerI(0.0, 0.0);
    if (!(value.lo >= 0.0) || value.lo > value.hi || !M8FlowerIsFinite(value.hi))
        return false;
    float2 values=float2(value.lo,value.hi);
    precise float2 rounded=0.0;
    [loop] for(uint endpoint=0u;endpoint<2u;endpoint++)
        rounded[endpoint]=M8FlowerRoundSqrt(values[endpoint]);
    float2 enclosed=float2(max(0.0,M8FlowerPrevious(rounded.x)),M8FlowerNext(rounded.y));
    if(!M8FlowerIsFinite(enclosed.y))return false;
    [loop] for(uint endpoint=0u;endpoint<2u;endpoint++)
    {
        int comparison=M8FlowerCompareDyadic(M8FlowerSquareDyadic(enclosed[endpoint]),
            M8FlowerProductDyadic(values[endpoint],1.0));
        if(endpoint==0u?comparison>0:comparison<0)return false;
    }
    result = M8FlowerI(enclosed.x,enclosed.y);
    return true;
}

float M8FlowerAbsoluteProductSumUpper(float3 a, float3 b)
{
    precise float3 product = a * b;
    float3 upper = float3(M8FlowerNext(abs(product.x)),
        M8FlowerNext(abs(product.y)), M8FlowerNext(abs(product.z)));
    precise float xy = upper.x + upper.y;
    precise float xyz = M8FlowerNext(xy) + upper.z;
    return M8FlowerNext(xyz);
}

M8FlowerInterval M8FlowerCenterRadius(float center, float radius)
{
    precise float lo = center - radius;
    precise float hi = center + radius;
    return M8FlowerI(M8FlowerPrevious(lo), M8FlowerNext(hi));
}

// Section 5: the caller supplies the frozen calibrated + quantization
// uncertainty, never an observation score or a manually selected epsilon.
// relative is the loop-center displacement from this endpoint's M8 owner.
bool M8FlowerPlaneIntervals(float3 normal, float offset, float3 relative,
    float radius, uint lineClass, float normalUncertainty, float offsetUncertainty,
    out M8FlowerInterval3 abc)
{
    abc.x = M8FlowerI(0.0, 0.0); abc.y = abc.x; abc.z = abc.x;
    if (lineClass >= M8_FLOWER_LINE_CLASS_COUNT ||
        !all(M8FlowerIsFinite(normal)) || !all(M8FlowerIsFinite(relative)) ||
        !all(M8FlowerIsFinite(float4(offset, radius, normalUncertainty, offsetUncertainty))) ||
        radius <= 0.0 || normalUncertainty < 0.0 || offsetUncertainty < 0.0)
        return false;
    float3 e1 = M8FlowerLineE1[lineClass];
    float3 e2 = M8FlowerLineE2[lineClass];
    precise float3 ar = normal * relative;
    precise float axy = ar.x + ar.y;
    precise float a = (axy + ar.z) - offset;
    precise float3 br = normal * e1;
    precise float bxy = br.x + br.y;
    precise float b = radius * (bxy + br.z);
    precise float3 cr = normal * e2;
    precise float cxy = cr.x + cr.y;
    precise float c = radius * (cxy + cr.z);

    M8FlowerInterval lengthSquared = M8FlowerIAdd(M8FlowerIAdd(
        M8FlowerISquare(M8FlowerI(relative.x, relative.x)),
        M8FlowerISquare(M8FlowerI(relative.y, relative.y))),
        M8FlowerISquare(M8FlowerI(relative.z, relative.z)));
    M8FlowerInterval length = M8FlowerI(0.0, 0.0);
    if (!M8FlowerISqrt(lengthSquared, length)) return false;
    precise float sa = M8FlowerAbsoluteProductSumUpper(normal, relative) + abs(offset);
    precise float sb = radius * M8FlowerAbsoluteProductSumUpper(normal, e1);
    precise float sc = radius * M8FlowerAbsoluteProductSumUpper(normal, e2);
    precise float eaMetric = normalUncertainty * length.hi;
    precise float eaOffset = M8FlowerNext(eaMetric) + offsetUncertainty;
    precise float eaRound = M8_FLOWER_GAMMA6_UPPER * M8FlowerNext(sa);
    precise float ea = M8FlowerNext(eaOffset) + M8FlowerNext(eaRound);
    precise float radialMetric = radius * normalUncertainty;
    precise float ebRound = M8_FLOWER_GAMMA7_UPPER * M8FlowerNext(sb);
    precise float ecRound = M8_FLOWER_GAMMA7_UPPER * M8FlowerNext(sc);
    precise float eb = M8FlowerNext(radialMetric) + M8FlowerNext(ebRound);
    precise float ec = M8FlowerNext(radialMetric) + M8FlowerNext(ecRound);
    abc.x = M8FlowerCenterRadius(a, M8FlowerNext(ea));
    abc.y = M8FlowerCenterRadius(b, M8FlowerNext(eb));
    abc.z = M8FlowerCenterRadius(c, M8FlowerNext(ec));
    return all(M8FlowerIsFinite(float3(abc.x.lo, abc.y.lo, abc.z.lo))) &&
        all(M8FlowerIsFinite(float3(abc.x.hi, abc.y.hi, abc.z.hi)));
}

uint M8FlowerRootInterval(M8FlowerInterval3 abc, bool plusRoot,
    out M8FlowerInterval2 root)
{
    root.x = M8FlowerI(0.0, 0.0);
    root.y = root.x;
    if (!all(M8FlowerIsFinite(float3(abc.x.lo, abc.y.lo, abc.z.lo))) ||
        !all(M8FlowerIsFinite(float3(abc.x.hi, abc.y.hi, abc.z.hi))) ||
        abc.x.lo > abc.x.hi || abc.y.lo > abc.y.hi || abc.z.lo > abc.z.hi)
        return M8_FLOWER_ROOT_AMBIGUOUS;
    uint classification = M8FlowerClassifyRoot(abc);
    if (classification != M8_FLOWER_ROOT_CERTAIN_SECANT &&
        classification != M8_FLOWER_ROOT_CERTAIN_TANGENT) return classification;
    M8FlowerInterval q = M8FlowerIAdd(M8FlowerISquare(abc.y),
        M8FlowerISquare(abc.z));
    M8FlowerInterval minusA = M8FlowerI(-abc.x.hi, -abc.x.lo);
    M8FlowerInterval x = M8FlowerIMul(minusA, abc.y);
    M8FlowerInterval y = M8FlowerIMul(minusA, abc.z);
    // Exact singleton tangency was established by dyadic equality, so no
    // uncertain subtraction around delta=0 is used to invent a second root.
    if (classification == M8_FLOWER_ROOT_CERTAIN_SECANT)
    {
        M8FlowerInterval delta = M8FlowerISub(q, M8FlowerISquare(abc.x));
        M8FlowerInterval turn = M8FlowerI(0.0, 0.0);
        if (!M8FlowerISqrt(delta, turn)) return M8_FLOWER_ROOT_AMBIGUOUS;
        if (!plusRoot) turn = M8FlowerI(-turn.hi, -turn.lo);
        x = M8FlowerIAdd(x, M8FlowerIMul(turn, M8FlowerI(-abc.z.hi, -abc.z.lo)));
        y = M8FlowerIAdd(y, M8FlowerIMul(turn, abc.y));
    }
    bool valid=true;
    [loop]for(uint axis=0u;axis<2u;axis++)
    {
        M8FlowerInterval numerator;
        if(axis==0u)numerator=x;else numerator=y;
        M8FlowerInterval component;
        bool componentValid=M8FlowerIDivPositive(numerator,q,component);
        if(axis==0u)root.x=component;else root.y=component;
        valid=valid && componentValid;
    }
    if(!valid)return M8_FLOWER_ROOT_AMBIGUOUS;
    return classification;
}

M8FlowerInterval M8FlowerICross(M8FlowerInterval2 a, M8FlowerInterval2 b)
{
    return M8FlowerISub(M8FlowerIMul(a.x, b.y), M8FlowerIMul(a.y, b.x));
}

bool M8FlowerRootSector(uint lineClass, M8FlowerInterval2 root, out uint sector)
{
    sector = 0xffffffffu;
    if (lineClass >= M8_FLOWER_LINE_CLASS_COUNT) return false;
    uint3 meta = M8FlowerLineMeta[lineClass];
    [loop]
    for (uint candidate = 0u; candidate < meta.z; candidate++)
    {
        float4 a = M8FlowerSectorBounds[meta.y + candidate];
        uint next = candidate + 1u == meta.z ? 0u : candidate + 1u;
        float4 b = M8FlowerSectorBounds[meta.y + next];
        M8FlowerInterval2 start, end;
        start.x = M8FlowerI(a.x, a.y); start.y = M8FlowerI(a.z, a.w);
        end.x = M8FlowerI(b.x, b.y); end.y = M8FlowerI(b.z, b.w);
        if (M8FlowerICross(start, root).lo > 0.0 &&
            M8FlowerICross(root, end).lo > 0.0)
        {
            if (sector != 0xffffffffu) { sector = 0xffffffffu; return false; }
            sector = candidate;
        }
    }
    return sector != 0xffffffffu;
}

int3 M8FlowerOverlapDelta(uint ordinal)
{
    return int3(ordinal & 1u, (ordinal >> 1u) & 1u, (ordinal >> 2u) & 1u);
}

uint M8FlowerOverlapBoundaryMask(int3 firstOwner, uint shift)
{
    uint mask = (1u << shift) - 1u;
    bool3 crosses = (asuint(firstOwner) & mask) == mask;
    return (crosses.x ? 1u : 0u) | (crosses.y ? 2u : 0u) |
        (crosses.z ? 4u : 0u);
}

int3 M8FlowerJunction(int3 kernel, int3 direction)
{
    return kernel * 2 + direction;
}

uint M8FlowerJunctionParity(int3 junction)
{
    uint3 u = asuint(junction);
    return (u.x & 1u) + (u.y & 1u) + (u.z & 1u);
}

bool M8FlowerEndpointPair(int3 junction, uint lineClass,
    out int3 first, out int3 second)
{
    int3 direction = M8FlowerLineDirection[lineClass];
    int3 doubled = junction-direction;
    if (any((asuint(doubled) & 1u) != 0u))
    {
        first = 0;
        second = 0;
        return false;
    }
    first = doubled >> 1;
    second = first+direction;
    return true;
}

float M8FlowerLevelStep(uint level)
{
    return M8_FLOWER_LATTICE_STEP / float(1u << level);
}

bool M8FlowerRoot(float3 abc, bool plusRoot, out float2 root)
{
    precise float q = abc.y*abc.y+abc.z*abc.z;
    precise float delta = q-abc.x*abc.x;
    if (!(q > 0.0) || delta < 0.0) { root = 0.0.xx; return false; }
    precise float d = sqrt(delta);
    precise float s = plusRoot ? 1.0 : -1.0;
    root = float2((-abc.x*abc.y + s*d*-abc.z)/q,
        (-abc.x*abc.z + s*d*abc.y)/q);
    return true;
}

bool M8FlowerTauInterval(M8FlowerInterval2 from, M8FlowerInterval2 to,
    out M8FlowerInterval turn)
{
    M8FlowerInterval denominator = M8FlowerIAdd(M8FlowerI(1.0,1.0),
        M8FlowerIAdd(M8FlowerIMul(from.x,to.x),
            M8FlowerIMul(from.y,to.y)));
    return M8FlowerIDivPositive(M8FlowerICross(from,to),denominator,turn);
}

bool M8FlowerSealRootIntervals(M8FlowerInterval2 first, M8FlowerInterval2 second,
    out M8FlowerInterval2 seal)
{
    seal.x = M8FlowerI(0.0,0.0);
    seal.y = M8FlowerI(0.0,0.0);
    M8FlowerInterval x = M8FlowerIAdd(first.x,second.x);
    M8FlowerInterval y = M8FlowerIAdd(first.y,second.y);
    M8FlowerInterval length;
    if (!M8FlowerISqrt(M8FlowerIAdd(M8FlowerISquare(x),
            M8FlowerISquare(y)),length) || !(length.lo > 0.0))return false;
    [loop]for(uint axis=0u;axis<2u;axis++)
    {
        M8FlowerInterval numerator;
        if(axis==0u)numerator=x;else numerator=y;
        M8FlowerInterval component;
        bool valid=M8FlowerIDivPositive(numerator,length,component);
        if(axis==0u)seal.x=component;else seal.y=component;
        if(!valid)return false;
    }
    return true;
}

bool M8FlowerSealBend(M8FlowerInterval2 first, M8FlowerInterval2 second,
    uint lineClass, out M8FlowerInterval2 seal, out M8FlowerInterval bend,
    out uint sector)
{
    seal.x = M8FlowerI(0.0,0.0);
    seal.y = M8FlowerI(0.0,0.0);
    bend = M8FlowerI(0.0,0.0);
    sector = 0u;
    uint secondSector;
    if (!M8FlowerRootSector(lineClass,first,sector) ||
        !M8FlowerRootSector(lineClass,second,secondSector) ||
        sector != secondSector || !M8FlowerSealRootIntervals(first,second,seal)) return false;
    uint sharedSector;
    if (!M8FlowerRootSector(lineClass,seal,sharedSector) ||
        sharedSector != sector) return false;
    // Contract 9.1: qB is the turn from the shared seal to the SECOND
    // endpoint, not the full first-to-second phase displacement.
    return M8FlowerTauInterval(seal,second,bend);
}

bool M8FlowerRotatePhaseMetric(M8FlowerInterval2 prediction,
    M8FlowerInterval turn, out M8FlowerInterval2 root)
{
    root.x = M8FlowerI(0.0,0.0);
    root.y = M8FlowerI(0.0,0.0);
    M8FlowerInterval squared = M8FlowerISquare(turn);
    M8FlowerInterval denominator = M8FlowerIAdd(M8FlowerI(1.0,1.0),squared);
    M8FlowerInterval c,s;
    c=M8FlowerI(0.0,0.0);s=c;
    [loop]for(uint axis=0u;axis<2u;axis++)
    {
        M8FlowerInterval numerator;
        if(axis==0u)numerator=M8FlowerISub(M8FlowerI(1.0,1.0),squared);
        else numerator=M8FlowerIMul(M8FlowerI(2.0,2.0),turn);
        M8FlowerInterval component;
        if(!M8FlowerIDivPositive(numerator,denominator,component))return false;
        if(axis==0u)c=component;else s=component;
    }
    root.x = M8FlowerISub(M8FlowerIMul(c,prediction.x),
        M8FlowerIMul(s,prediction.y));
    root.y = M8FlowerIAdd(M8FlowerIMul(s,prediction.x),
        M8FlowerIMul(c,prediction.y));
    return all(M8FlowerIsFinite(float4(root.x.lo,root.x.hi,root.y.lo,root.y.hi)));
}

bool M8FlowerRotateInterval(M8FlowerInterval2 prediction,
    M8FlowerInterval turn, uint lineClass, uint sector,
    out M8FlowerInterval2 root)
{
    root.x = M8FlowerI(0.0,0.0);
    root.y = M8FlowerI(0.0,0.0);
    uint predictedSector;
    if (!M8FlowerRootSector(lineClass,prediction,predictedSector) ||
        predictedSector != sector || !M8FlowerRotatePhaseMetric(prediction,turn,root)) return false;
    uint synthesizedSector;
    return M8FlowerRootSector(lineClass,root,synthesizedSector) &&
        synthesizedSector == sector;
}

bool M8FlowerTau(float2 from, float2 to, out float turn)
{
    precise float denominator = 1.0+dot(from,to);
    if (denominator == 0.0) { turn = 0.0; return false; }
    turn = (from.x*to.y-from.y*to.x)/denominator;
    return true;
}

float2 M8FlowerRotate(float2 root, float turn)
{
    precise float rr = turn*turn;
    precise float inverse = 1.0/(1.0+rr);
    precise float c = (1.0-rr)*inverse;
    precise float s = 2.0*turn*inverse;
    return float2(c*root.x-s*root.y,s*root.x+c*root.y);
}

#define M8_FLOWER_PHASE_IMPOSSIBLE 0u
#define M8_FLOWER_PHASE_EXACT_ZERO 1u
#define M8_FLOWER_PHASE_CERTAIN_NONZERO 2u
#define M8_FLOWER_PHASE_AMBIGUOUS 3u
#define M8_FLOWER_PHASE_PROMOTE 4u
#define M8_FLOWER_BOUNDARY_WITNESS_MASK (63u<<21u)

struct M8FlowerPhaseRootEvidence
{
    int3 Junction;
    uint Tag;
    M8FlowerInterval2 Root;
    uint Classification; // ProofClassification: impossible=0,certain=1,ambiguous=2
};

