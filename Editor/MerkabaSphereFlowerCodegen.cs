bool M8FlowerSkinSplitClosure(uint splitL2, uint splitL3, uint2 splitL4)
{
    if ((splitL3&~0x7fu)!=0u || (splitL4.y&~0x1ffffu)!=0u)
        return false;
    if (splitL2==0u)
        return splitL3==0u && all(splitL4==0u.xx);
    [unroll]
    for (uint parent=0u;parent<7u;parent++)
    {
        if ((splitL3&(1u<<parent))!=0u) continue;
        [unroll]
        for (uint child=0u;child<7u;child++)
        {
            uint bit=7u*parent+child;
            uint value=bit<32u ? splitL4.x : splitL4.y;
            uint shift=bit<32u ? bit : bit-32u;
            if ((value&(1u<<shift))!=0u) return false;
        }
    }
    return true;
}

