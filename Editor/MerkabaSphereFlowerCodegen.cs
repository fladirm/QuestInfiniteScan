    uint source=M8FlowerL2Wedge[6u*carrier].y;
    return source |
        (rootSign ? (1u<<M8_FLOWER_L2_KEY_ROOT_SHIFT) : 0u) |
        (sector<<M8_FLOWER_L2_KEY_SECTOR_SHIFT);
}

