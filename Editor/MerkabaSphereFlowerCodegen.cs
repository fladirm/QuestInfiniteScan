float M8FlowerNext(float v)
{
    uint b = asuint(v);
    if ((b & 0x7fffffffu) == 0u) return asfloat(1u);
    if (b == 0x7f800000u) return v;
    return asfloat((b & 0x80000000u) == 0u ? b + 1u : b - 1u);
}

float M8FlowerPrevious(float v)
{
    uint b = asuint(v);
    if ((b & 0x7fffffffu) == 0u) return asfloat(0x80000001u);
    if (b == 0xff800000u) return v;
    return asfloat((b & 0x80000000u) == 0u ? b - 1u : b + 1u);
}

M8FlowerInterval M8FlowerI(float lo, float hi)
{
    M8FlowerInterval r; r.lo = lo; r.hi = hi; return r;
}

M8FlowerInterval M8FlowerIAdd(M8FlowerInterval a, M8FlowerInterval b)
{
    precise float lo = a.lo+b.lo;
    precise float hi = a.hi+b.hi;
    return M8FlowerI(M8FlowerPrevious(lo),M8FlowerNext(hi));
}

M8FlowerInterval M8FlowerISub(M8FlowerInterval a, M8FlowerInterval b)
{
    precise float lo = a.lo-b.hi;
    precise float hi = a.hi-b.lo;
    return M8FlowerI(M8FlowerPrevious(lo),M8FlowerNext(hi));
}

M8FlowerInterval M8FlowerIMul(M8FlowerInterval a, M8FlowerInterval b)
{
    precise float4 p = float4(a.lo * b.lo, a.lo * b.hi,
        a.hi * b.lo, a.hi * b.hi);
    return M8FlowerI(M8FlowerPrevious(min(min(p.x,p.y),min(p.z,p.w))),
        M8FlowerNext(max(max(p.x,p.y),max(p.z,p.w))));
}

M8FlowerInterval M8FlowerISquare(M8FlowerInterval a)
{
    if (a.lo <= 0.0 && a.hi >= 0.0)
        return M8FlowerI(0.0,
            M8FlowerNext(max(a.lo*a.lo,a.hi*a.hi)));
    return M8FlowerIMul(a,a);
}

struct M8FlowerDyadicSquare
{
    uint2 coefficient;
    int exponent;
    uint nonzero;
};

uint2 M8FlowerMultiply24(uint a, uint b)
{
    uint a0 = a & 0xffffu;
    uint a1 = a >> 16;
    uint b0 = b & 0xffffu;
    uint b1 = b >> 16;
    uint p0 = a0*b0;
    uint p1 = a0*b1+a1*b0;
    uint lo = p0+(p1 << 16);
    uint carry = lo < p0 ? 1u : 0u;
    uint hi = (p1 >> 16)+a1*b1+carry;
    return uint2(lo,hi);
}

M8FlowerDyadicSquare M8FlowerSquareDyadic(float value)
{
    M8FlowerDyadicSquare result;
    uint bits = asuint(abs(value));
    uint exponentBits = (bits >> 23) & 0xffu;
    uint mantissa = bits & 0x7fffffu;
    result.nonzero = 0u;
    result.coefficient = 0u.xx;
    result.exponent = 0;
    if (exponentBits == 0xffu)
    {
        result.nonzero = 2u;
        return result;
    }
    if (exponentBits == 0u && mantissa == 0u)
        return result;
    int exponent = exponentBits == 0u ? -149 : (int)exponentBits-127-23;
    if (exponentBits != 0u) mantissa |= 0x800000u;
    int trailing = firstbitlow(mantissa);
    mantissa >>= trailing;
    exponent += trailing;
    result.coefficient = M8FlowerMultiply24(mantissa,mantissa);
    result.exponent = exponent*2;
    result.nonzero = 1u;
    return result;
}

uint M8FlowerBitLength(uint2 value)
{
    return value.y != 0u ? 33u+(uint)firstbithigh(value.y) :
        (value.x != 0u ? 1u+(uint)firstbithigh(value.x) : 0u);
}

bool M8FlowerEqual64(uint2 a, uint2 b)
{
    return all(a == b);
}

uint2 M8FlowerAdd64(uint2 a, uint2 b)
{
    uint lo = a.x+b.x;
    return uint2(lo,a.y+b.y+(lo < a.x ? 1u : 0u));
}

uint2 M8FlowerShiftLeft64(uint2 value, uint shift)
{
    if (shift == 0u) return value;
    if (shift < 32u)
        return uint2(value.x << shift,
            (value.y << shift) | (value.x >> (32u-shift)));
    if (shift < 64u) return uint2(0u,value.x << (shift-32u));
    return 0u.xx;
}

uint2 M8FlowerShiftRightOne64(uint2 value)
{
    return uint2((value.x >> 1) | (value.y << 31),value.y >> 1);
}

bool M8FlowerExactSquaredEquality(float a, float b, float c)
{
    M8FlowerDyadicSquare sa = M8FlowerSquareDyadic(a);
    M8FlowerDyadicSquare sb = M8FlowerSquareDyadic(b);
    M8FlowerDyadicSquare sc = M8FlowerSquareDyadic(c);
    if (sa.nonzero == 2u || sb.nonzero == 2u || sc.nonzero == 2u)
        return false;
    if (sb.nonzero == 0u && sc.nonzero == 0u)
        return sa.nonzero == 0u;
    if (sa.nonzero == 0u) return false;
    if (sb.nonzero == 0u)
        return sa.exponent == sc.exponent &&
            M8FlowerEqual64(sa.coefficient,sc.coefficient);
    if (sc.nonzero == 0u)
        return sa.exponent == sb.exponent &&
            M8FlowerEqual64(sa.coefficient,sb.coefficient);

    if (sb.exponent == sc.exponent)
    {
        uint2 sum = M8FlowerAdd64(sb.coefficient,sc.coefficient);
        return sa.exponent == sb.exponent+1 &&
            M8FlowerEqual64(sa.coefficient,M8FlowerShiftRightOne64(sum));
    }

    M8FlowerDyadicSquare low;
    M8FlowerDyadicSquare high;
    if (sb.exponent < sc.exponent)
    {
        low = sb;
        high = sc;
    }
    else
    {
        low = sc;
        high = sb;
    }
    int difference = high.exponent-low.exponent;
    if (sa.exponent != low.exponent || difference >= 64)
        return false;
    uint highBits = M8FlowerBitLength(high.coefficient);
    uint leftBits = M8FlowerBitLength(sa.coefficient);
    if (highBits+(uint)difference > leftBits)
        return false;
    uint2 sum = M8FlowerAdd64(low.coefficient,
        M8FlowerShiftLeft64(high.coefficient,(uint)difference));
    return M8FlowerEqual64(sa.coefficient,sum);
}

uint M8FlowerClassifyRoot(M8FlowerInterval3 abc)
{
    if (abc.x.lo == abc.x.hi && abc.y.lo == abc.y.hi &&
        abc.z.lo == abc.z.hi &&
        M8FlowerExactSquaredEquality(abc.x.lo,abc.y.lo,abc.z.lo))
        return abc.y.lo == 0.0 && abc.z.lo == 0.0 ?
            M8_FLOWER_ROOT_COPLANAR : M8_FLOWER_ROOT_CERTAIN_TANGENT;
    M8FlowerInterval q = M8FlowerIAdd(M8FlowerISquare(abc.y),
        M8FlowerISquare(abc.z));
    M8FlowerInterval aa = M8FlowerISquare(abc.x);
    if (q.lo == 0.0 && q.hi == 0.0)
    {
        if (abc.x.lo == abc.x.hi)
            return abc.x.lo == 0.0 ? M8_FLOWER_ROOT_COPLANAR :
                M8_FLOWER_ROOT_IMPOSSIBLE;
        return abc.x.lo <= 0.0 && abc.x.hi >= 0.0 ?
            M8_FLOWER_ROOT_AMBIGUOUS : M8_FLOWER_ROOT_IMPOSSIBLE;
    }
    if (aa.hi < q.lo) return M8_FLOWER_ROOT_CERTAIN_SECANT;
    if (aa.lo > q.hi) return M8_FLOWER_ROOT_IMPOSSIBLE;
    if (aa.lo == aa.hi && q.lo == q.hi && aa.lo == q.lo && q.lo > 0.0)
        return M8_FLOWER_ROOT_CERTAIN_TANGENT;
    return M8_FLOWER_ROOT_AMBIGUOUS;
}

