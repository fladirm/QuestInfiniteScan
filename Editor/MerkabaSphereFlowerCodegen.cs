void M8FlowerSkinSortPair(inout uint left, inout uint right,
    float3 values, uint3 sites)
{
    if (M8FlowerSkinBefore(values[left],sites[left],
            values[right],sites[right])) return;
    uint swap=left; left=right; right=swap;
}

uint M8FlowerSkinOrder(float3 barycentric, uint wedge)
{
    uint3 sites=M8FlowerSkinWedgeSites(wedge);
    uint high=0u,middle=1u,low=2u;
    M8FlowerSkinSortPair(high,middle,barycentric,sites);
    M8FlowerSkinSortPair(middle,low,barycentric,sites);
    M8FlowerSkinSortPair(high,middle,barycentric,sites);
    if (high==0u) return middle==1u ? 0u : 1u;
    if (high==1u) return middle==0u ? 2u : 3u;
    return middle==0u ? 4u : 5u;
}

float3 M8FlowerSkinApplyChamber(float3 value, int3 order)
{
    precise float x0=value[order.x];
    precise float x1=value[order.y];
    precise float x2=value[order.z];
    return float3(x0-x1,2.0*(x1-x2),3.0*x2);
}

